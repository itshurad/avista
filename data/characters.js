export function transliterationToAvestan(transliteration) {
  if (!transliteration) return "";

  let result = "";
  let i = 0;

  while (i < transliteration.length) {
    let matched = false;

    // بررسی ترکیب‌های چند کاراکتری (از بلندترین شروع می‌کنیم)
    for (let len = 4; len >= 1; len--) {
      if (i + len > transliteration.length) continue;
      const substring = transliteration.substring(i, i + len);
      if (transliterationMap[substring]) {
        result += transliterationMap[substring];
        i += len;
        matched = true;
        break;
      }
    }

    if (!matched) {
      result += transliteration[i];
      i++;
    }
  }

  return result;
}

