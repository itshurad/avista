/**
 * استخراج امن و بهینهٔ نویسه‌های یونیکد دین‌دبیره
 * فقط کاراکترهای بازهٔ U+10B00 تا U+10B3F را استخراج می‌کند.
 */
export function getUniqueAvestanGlyphs(wordStr) {
  if (!wordStr || typeof wordStr !== "string") return [];
  const avestanRegex = /[\u{10B00}-\u{10B3F}]/gu;
  const glyphs = wordStr.match(avestanRegex) || [];
  return [...new Set(glyphs)];
}

