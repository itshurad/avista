/**
 * ساختار نهایی دیکشنری با فرمت استاندارد و بهینه برای مصرف در UI/Backend
 * @type {Array<Object>}
 */
export const dictionaryData = Object.freeze(
  coreHistoricalCorpus.map((entry, idx) => ({
    id: `av_${String(idx + 1).padStart(4, "0")}`,
    avestan: entry.av,
    transliteration: entry.tr,
    pronunciation: entry.pr,
    partOfSpeech: entry.pos,
    category: entry.cat,
    meaning: entry.m,
    root: entry.r,
    gathicContext: entry.ctx,
    academicSource: entry.source,
    relatedCharacters: getUniqueAvestanGlyphs(entry.av),
  })),
);

/**
 * تابع جستجوی پیشرفته و بهینه در دیکشنری
 * از الگوریتم‌های بهینه برای جستجو در چندین فیلد به‌صورت همزمان استفاده می‌کند.
 */
export function searchAvestanDictionary(query) {
  if (!query || typeof query !== "string") return [];
  const lowerQuery = query.toLowerCase().trim();

  return dictionaryData.filter(
    (item) =>
      item.avestan.includes(query) ||
      item.transliteration.toLowerCase().includes(lowerQuery) ||
      item.pronunciation.includes(lowerQuery) ||
      item.meaning.includes(lowerQuery) ||
      item.root.toLowerCase().includes(lowerQuery),
  );
}

